"""Optional Ollama adapter, using only urllib and explicit evidence context."""
from __future__ import annotations
import json
from urllib.request import Request, urlopen
from urllib.error import HTTPError, URLError
from .analysis import Analysis
from .models import Paper
class OllamaError(RuntimeError): pass
class OllamaAnalyzer:
    def __init__(self, model="llama3.2", endpoint="http://localhost:11434/api/generate", timeout=60, opener=urlopen):
        self.model, self.endpoint, self.timeout, self.opener = model, endpoint, timeout, opener
    def analyze(self, papers: list[Paper], question: str) -> Analysis:
        evidence = "\n".join(f"[{i+1}] {p.title} ({p.publication_year or 'n.d.'}) — {p.abstract[:1000]}" for i,p in enumerate(papers))
        prompt = f"Answer only from the evidence below. Say when evidence is insufficient.\nQuestion: {question}\nEvidence:\n{evidence}"
        body = json.dumps({"model": self.model, "prompt": prompt, "stream": False}).encode()
        try:
            req = Request(self.endpoint, data=body, headers={"Content-Type": "application/json"})
            with self.opener(req, timeout=self.timeout) as r: result = json.loads(r.read().decode())
            return Analysis(str(result.get("response", "")), tuple(p.title for p in papers), ("Generated by an optional local model; verify claims against sources.",))
        except (HTTPError, URLError, TimeoutError, OSError, json.JSONDecodeError, ValueError) as e:
            raise OllamaError(f"Ollama request failed: {e}") from e
